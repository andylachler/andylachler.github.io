#!/usr/bin/env node
// build-image-manifest.js — scans images/<project-id>/ folders and writes
// images/manifest.js (window.IMAGE_MANIFEST) for the site to read.
//
// Convention per folder (images/<project-id>/):
//   tile.(jpg|jpeg|png|webp|avif)   → grid/carousel/dropdown tile image
//   hero.(jpg|jpeg|png|webp|avif)   → case-study hero (falls back to tile)
//   01.jpg, 02.png, …               → gallery, sorted numerically
//   book-01.jpg, book-02.jpg, …     → portfolio-book spreads, sorted numerically
//   captions.json                   → optional: { "01": "Caption text", "book-01": "…", … }
//
// Run from the portfolio root:  node tools/build-image-manifest.js
// Warns about files >600KB (resize/compress before shipping).

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const IMAGES = path.join(ROOT, 'images');
const OUT = path.join(IMAGES, 'manifest.js');
const EXT = /\.(jpe?g|png|webp|avif|gif)$/i;
const VID = /\.(mp4|webm)$/i;
const SIZE_WARN = 600 * 1024;

const manifest = {};
const warnings = [];

if (!fs.existsSync(IMAGES)) fs.mkdirSync(IMAGES);

for (const dir of fs.readdirSync(IMAGES, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const id = dir.name;
  const folder = path.join(IMAGES, id);
  const entry = {};
  let captions = {};

  const capPath = path.join(folder, 'captions.json');
  if (fs.existsSync(capPath)) {
    try { captions = JSON.parse(fs.readFileSync(capPath, 'utf8')); }
    catch (e) { warnings.push(`${id}/captions.json is invalid JSON — captions skipped`); }
  }

  const gallery = [];
  const book = [];
  for (const f of fs.readdirSync(folder).sort()) {
    const isVid = VID.test(f);
    if (!EXT.test(f) && !isVid) continue;
    const rel = `images/${id}/${f}`;
    let base = f.replace(EXT, '').replace(VID, '');
    // HERO / Hero / TILE etc. — Andy labels hero images "HERO" in the sources;
    // accept any casing (and stray trailing spaces) for the special names.
    if (/^\s*hero\s*$/i.test(base)) base = 'hero';
    if (/^\s*tile\s*$/i.test(base)) base = 'tile';
    const { size } = fs.statSync(path.join(folder, f));
    if (size > (isVid ? 60 * 1024 * 1024 : SIZE_WARN)) warnings.push(`${rel} is ${(size / 1024 / 1024).toFixed(1)}MB — compress it`);

    if (base === 'tile') entry.tile = rel;
    else if (base === 'hero') entry.hero = rel;
    else if (/^\d+$/.test(base)) gallery.push({ n: parseInt(base, 10), src: rel, video: isVid || undefined, caption: captions[base] || captions[f] || null });
    else if (/^book-\d+$/.test(base)) book.push({ n: parseInt(base.slice(5), 10), src: rel, caption: captions[base] || captions[f] || null });
    else warnings.push(`${rel} ignored — name it tile.*, hero.*, a number (01.jpg), or book-NN.jpg`);
  }
  gallery.sort((a, b) => a.n - b.n);
  if (gallery.length) entry.gallery = gallery.map(({ src, caption, video }) => ({ src, ...(video ? { video: true } : {}), ...(caption ? { caption } : {}) }));
  book.sort((a, b) => a.n - b.n);
  if (book.length) entry.book = book.map(({ src, caption }) => ({ src, ...(caption ? { caption } : {}) }));

  if (Object.keys(entry).length) manifest[id] = entry;
}

const body = '// AUTO-GENERATED by tools/build-image-manifest.js — do not edit.\n' +
  '// Add/remove files in images/<project-id>/ and re-run the script.\n' +
  'window.IMAGE_MANIFEST = ' + JSON.stringify(manifest, null, 2) + ';\n';
fs.writeFileSync(OUT, body);

const n = Object.keys(manifest).length;
console.log(`manifest.js written — ${n} project${n === 1 ? '' : 's'} with images`);
for (const w of warnings) console.warn('⚠ ' + w);
